// Copies shared/rt-client.js into both front-ends.
//   client-agent/src/rt-client.js  -> ES module (verbatim)
//   embed_widget/rt-client.js      -> classic script exposing window.__EFX_CHAT_IO__ (not window.io, to avoid
//                                     clashing with a socket.io the host page may already load)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'shared', 'rt-client.js'), 'utf8');
const banner = '// GENERATED by scripts/sync-rt-client.mjs from shared/rt-client.js - do not edit.\n';

writeFileSync(join(root, 'client-agent', 'src', 'rt-client.js'), banner + source);

if (!/^export function io\(/m.test(source)) {
  throw new Error('shared/rt-client.js must declare `export function io(`');
}
const classic = source.replace(/^export function io\(/m, 'function io(');
writeFileSync(
  join(root, 'embed_widget', 'rt-client.js'),
  `${banner}(function () {\n'use strict'\n${classic}\nwindow.__EFX_CHAT_IO__ = io\n})()\n`
);

console.log('rt-client synced to client-agent/src and embed_widget');
